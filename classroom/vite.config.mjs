import { cpSync, existsSync, mkdirSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import { defineConfig } from 'vite';

const root = dirname(fileURLToPath(import.meta.url));

// Copies KaTeX CSS + fonts next to the IIFE so exam machines do not need a CDN.
// Official katex.min.css resolves fonts as url(fonts/…), so keep that layout.
function copyKatexAssets() {
  return {
    name: 'copy-katex-assets',
    closeBundle() {
      const srcCss = resolve(root, 'node_modules/katex/dist/katex.min.css');
      const srcFonts = resolve(root, 'node_modules/katex/dist/fonts');
      const destDir = resolve(root, 'resources/vendor');
      const destFonts = resolve(destDir, 'fonts');
      if (!existsSync(srcCss) || !existsSync(srcFonts)) {
        throw new Error('katex is not installed; run npm ci before npm run build:editor');
      }
      mkdirSync(destFonts, { recursive: true });
      cpSync(srcCss, resolve(destDir, 'katex.min.css'));
      cpSync(srcFonts, destFonts, { recursive: true });
    },
  };
}

export default defineConfig({
  plugins: [copyKatexAssets()],
  build: {
    lib: {
      entry: resolve(root, 'resources/js/rich_editor/index.js'),
      name: 'RichEditor',
      formats: ['iife'],
      fileName: () => 'rich_editor.js',
    },
    outDir: resolve(root, 'resources'),
    emptyOutDir: false,
    sourcemap: false,
    rollupOptions: {
      output: {
        inlineDynamicImports: true,
        entryFileNames: 'rich_editor.js',
        banner: '/* Generated by `npm run build:editor`. Edit resources/js/rich_editor/, not this file. */',
      },
    },
  },
  test: {
    environment: 'jsdom',
    include: ['resources/js/rich_editor/**/*.test.js'],
  },
});
