import { useEffect, useState } from "react";
import { scanAiApi, type CaptureLink } from "../../../api/scanAi";
import { errorText, formatWhen } from "../../../components/teacher/util";
import "../../../styles/scanAi.css";

/** "Use your phone" on the upload step: a QR code / short link to the capture page. */
export function PhoneCapture({ examId, unprinted }: { examId: string; unprinted: boolean }) {
  const [link, setLink] = useState<CaptureLink | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // a link is made for one mode: drop it when the mode changes
  useEffect(() => setLink(null), [unprinted]);

  async function open() {
    setBusy(true);
    setError(null);
    try {
      setLink(await scanAiApi.newCapture(examId, unprinted));
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="t-card" aria-labelledby="cap-h">
      <div className="sc-card-head">
        <div>
          <h3 id="cap-h">Use your phone</h3>
          <p className="t-muted sc-small">
            No scanner? Open the link on your phone, photograph the pages one after another and tap Send. No login needed
            on the phone; the link works for this exam for 30 minutes.
          </p>
        </div>
        <button type="button" className="btn btn-secondary" disabled={busy} onClick={open}>
          {busy ? "Opening…" : link ? "New link" : "Show QR code"}
        </button>
      </div>
      {error && (
        <p className="t-inline-error" role="alert">
          {error}
        </p>
      )}
      {link && (
        <div className="cap-qr">
          {/* SVG generated by our server from the link (no user content) */}
          <span aria-label="QR code for the phone link" role="img" dangerouslySetInnerHTML={{ __html: link.qr_svg }} />
          <div>
            <p className="cap-link">
              <a href={link.path} target="_blank" rel="noreferrer">
                {link.url}
              </a>
            </p>
            <p className="t-muted sc-small">Valid until {formatWhen(link.expires_at)}. Photos appear in Uploads below.</p>
            {link.url.includes("127.0.0.1") || link.url.includes("localhost") ? (
              <p className="sc-low sc-small">
                This server runs on this computer only: the phone must reach it on the same network (start it with
                HOST=0.0.0.0 and set FAIRPLAY_PUBLIC_URL).
              </p>
            ) : null}
          </div>
        </div>
      )}
    </section>
  );
}
